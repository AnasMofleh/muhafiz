const dictionaries: Record<AppLanguage, typeof en> = { en, sv, ar };

function resolve(dict: unknown, key: string): string | undefined {
  let node: unknown = dict;
  for (const part of key.split('.')) {
    if (node && typeof node === 'object' && part in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[part];
    } else {
      return undefined;
    }
  }
  return typeof node === 'string' ? node : undefined;
}

/** Translate a dot-path key, falling back to English (then the key itself). */
export function translate(language: AppLanguage, key: string): string {
  return resolve(dictionaries[language], key) ?? resolve(en, key) ?? key;
}

/** Interpolate {placeholders} in a translated string. */
export function fill(key: string, values: Record<string, string | number>): string {
  return key.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match
  );
}

/** Reactive translator hook — re-renders when the language changes. */
export function useT() {
  const language = useSettings((state) => state.language);
  return useMemo(() => {
    const t = (key: string, values?: Record<string, string | number>) => {
      const text = translate(language, key);
      return values ? fill(text, values) : text;
    };
    return t;
  }, [language]);
}
